# gen_keys.ps1 (11/16): embeds the keys into the builds, so no keys file is distributed.
#
#   Config\StreamingKeys.ini (repo root, NOT in git)  ->  Src\Stream\EmbeddedKeys.h       (supermodel.exe, NOT in git)
#                                                      ->  Launcher\PonLuncher\EmbeddedKeys.vb (PonLuncher.exe, NOT in git)
#
# Called by Makefiles/Makefile.Win32 (every make) and by the launcher's PonLuncher.vbproj (before each build).
# The values are stored XOR-scrambled, so they are not readable as plain text in the exe. That only keeps them out
# of casual sight: anything inside a distributed exe can be dug out. So only values that may be public go here
# (Firebase web API key / database URL, Discord client ID / guild ID / invite, the status webhook); the real defence
# is the Firebase rules and the host-side Discord check. Never a bot token or a client secret.
# A file is rewritten only when its content changes (no needless rebuilds). Without the ini, empty values are written
# (lobby and Discord are then off).

param(
  [string]$Root = (Split-Path -Parent $PSScriptRoot),
  [switch]$CppOnly,
  [switch]$VbOnly
)
$ErrorActionPreference = 'Stop'

$names = @('FirebaseApiKey', 'FirebaseDbUrl', 'DiscordClientId', 'DiscordGuildId', 'DiscordRedirectPort', 'DiscordInviteUrl', 'DiscordWebhookUrl', 'TicketUrl', 'TicketPublicKey')
$values = @{}
foreach ($n in $names) { $values[$n] = '' }
$ini = Join-Path $Root 'Config\StreamingKeys.ini'
if (Test-Path $ini) {
  foreach ($line in [IO.File]::ReadAllLines($ini)) {
    $t = $line.Trim()
    if ($t -eq '' -or $t.StartsWith(';') -or $t.StartsWith('#')) { continue }
    $eq = $t.IndexOf('=')
    if ($eq -lt 0) { continue }
    $k = $t.Substring(0, $eq).Trim()
    if ($values.ContainsKey($k)) { $values[$k] = $t.Substring($eq + 1).Trim().Trim('"') }
  }
}

function Scramble([string]$s, [int]$idx) {
  $bytes = [Text.Encoding]::UTF8.GetBytes($s)
  $out = New-Object byte[] $bytes.Length
  for ($i = 0; $i -lt $bytes.Length; $i++) { $out[$i] = $bytes[$i] -bxor ((0x5A + $i * 31 + $idx * 17) -band 0xFF) }
  return ,$out
}

function WriteIfChanged([string]$path, [string]$text) {
  $old = if (Test-Path $path) { [IO.File]::ReadAllText($path) } else { $null }
  if ($old -ne $text) { [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding($false))) }
}

$present = if (Test-Path $ini) { 'from Config\StreamingKeys.ini' } else { 'Config\StreamingKeys.ini not found: empty keys' }

if (-not $VbOnly) {
  $sb = New-Object Text.StringBuilder
  [void]$sb.AppendLine('// Generated by Scripts/gen_keys.ps1 ' + $present + '. NOT in git. Do not edit.')
  [void]$sb.AppendLine('#pragma once')
  [void]$sb.AppendLine('namespace EmbeddedKeys {')
  for ($i = 0; $i -lt $names.Count; $i++) {
    $b = Scramble $values[$names[$i]] $i
    $list = if ($b.Length) { ($b | ForEach-Object { '0x{0:X2}' -f $_ }) -join ',' } else { '0' }
    [void]$sb.AppendLine(('  static const unsigned char k{0}[] = {{{1}}}; static const int k{0}Len = {2};' -f $names[$i], $list, $b.Length))
  }
  [void]$sb.AppendLine('}')
  WriteIfChanged (Join-Path $Root 'Src\Stream\EmbeddedKeys.h') $sb.ToString()
}

if (-not $CppOnly) {
  $sb = New-Object Text.StringBuilder
  [void]$sb.AppendLine("' Generated by Scripts/gen_keys.ps1 " + $present + '. NOT in git. Do not edit.')
  [void]$sb.AppendLine('Friend Module EmbeddedKeys')
  for ($i = 0; $i -lt $names.Count; $i++) {
    $b = Scramble $values[$names[$i]] $i
    $list = ($b | ForEach-Object { '&H{0:X2}' -f $_ }) -join ', '
    [void]$sb.AppendLine(('    Friend ReadOnly {0} As Byte() = New Byte() {{{1}}}' -f $names[$i], $list))
  }
  [void]$sb.AppendLine('End Module')
  WriteIfChanged (Join-Path $Root 'Launcher\PonLuncher\EmbeddedKeys.vb') $sb.ToString()
}
