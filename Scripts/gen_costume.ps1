# gen_costume.ps1 (11/17): embeds the 8-player costume pictures into supermodel.exe, deflate-compressed.
#
#   Config\costume\*_col4..7_*.bmp (repo root, NOT in git)  ->  Src\Model3\EmbeddedCostume.h (NOT in git)
#
# Called by Makefiles/Makefile.Win32 on every make. The pictures are the ROM costumes recoloured (costume_recolor.py),
# so they are kept out of git; the exe carries them and no costume folder is needed next to it.
# Archive (before compression): for each file  [1 byte name length][name][4 bytes data length, little-endian][data].
# The header is rewritten only when a picture or this script is newer than it (no needless rebuilds).
# Without the folder an empty archive is written: CostumeSwap then falls back to a costume folder, if any.

param([string]$Root = (Split-Path -Parent $PSScriptRoot))
$ErrorActionPreference = 'Stop'

$srcDir = Join-Path $Root 'Config\costume'
$out = Join-Path $Root 'Src\Model3\EmbeddedCostume.h'
$files = @()
if (Test-Path $srcDir) { $files = @(Get-ChildItem $srcDir -File -Filter '*.bmp' | Where-Object { $_.Name -match '_col[4-7]_' } | Sort-Object Name) }

if (Test-Path $out) {
  $outTime = (Get-Item $out).LastWriteTimeUtc
  $newest = (Get-Item $PSCommandPath).LastWriteTimeUtc
  foreach ($f in $files) { if ($f.LastWriteTimeUtc -gt $newest) { $newest = $f.LastWriteTimeUtc } }
  $head = [IO.File]::ReadAllText($out).Substring(0, [Math]::Min(300, (Get-Item $out).Length))
  if ($outTime -gt $newest -and $head.Contains("files=$($files.Count) ")) { exit 0 }
}

$raw = New-Object IO.MemoryStream
foreach ($f in $files) {
  $name = [Text.Encoding]::ASCII.GetBytes($f.Name)
  $data = [IO.File]::ReadAllBytes($f.FullName)
  $raw.WriteByte([byte]$name.Length)
  $raw.Write($name, 0, $name.Length)
  $raw.Write([BitConverter]::GetBytes([uint32]$data.Length), 0, 4)
  $raw.Write($data, 0, $data.Length)
}
$rawBytes = $raw.ToArray()

$zs = New-Object IO.MemoryStream
$def = New-Object IO.Compression.DeflateStream($zs, [IO.Compression.CompressionLevel]::Optimal, $true)
$def.Write($rawBytes, 0, $rawBytes.Length)
$def.Dispose()
$z = $zs.ToArray()

$sb = New-Object Text.StringBuilder ($z.Length * 5 + 1024)
[void]$sb.AppendLine("// Generated by Scripts/gen_costume.ps1: files=$($files.Count) raw=$($rawBytes.Length) deflate=$($z.Length) . NOT in git. Do not edit.")
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('namespace EmbeddedCostume {')
[void]$sb.AppendLine("  static const unsigned int kRawLen = $($rawBytes.Length);")
[void]$sb.AppendLine("  static const unsigned int kZLen = $($z.Length);")
[void]$sb.Append('  static const unsigned char kZ[] = {')
if ($z.Length -eq 0) { [void]$sb.Append('0') }
for ($i = 0; $i -lt $z.Length; $i++) {
  if (($i % 32) -eq 0) { [void]$sb.Append("`n    ") }
  [void]$sb.Append($z[$i]).Append(',')
}
[void]$sb.AppendLine("`n  };")
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
